def record_planner_stage_duration(run_id: str | None, stage: str, duration_s: float) -> None:
    """Record planner stage duration in seconds using run+stage labels.

    Labels:
    - run_id: durable planner run identifier
    - stage: planner stage name (load_candidates/metadata_lookup/action_generation/persist_actions)

    This helper is intentionally fail-open so planner execution is never impacted
    by metrics registry/runtime errors.
    """
    if _PLANNER_STAGE_DURATION_SECONDS is None:
        return
    try:
        normalized_run_id = _normalize_run_id(run_id)
        _PLANNER_STAGE_DURATION_SECONDS.labels(run_id=normalized_run_id, stage=stage).observe(max(duration_s, 0.0))
    except Exception:
        logger.exception("Failed to record planner stage duration")


def record_canonical_read_cache_metrics(
    run_id: str | None,
    source: str,
    cache_hits: int,
    cache_misses: int,
) -> None:
    """Record canonical metadata read cache counters and ratio gauge.

    The cache exposes cumulative in-memory totals. This helper converts them into
    monotonic counter increments by tracking per-label previous totals.
    """
    if (
        _CANONICAL_READ_CACHE_HITS_TOTAL is None
        or _CANONICAL_READ_CACHE_MISSES_TOTAL is None
        or _CANONICAL_READ_CACHE_HIT_RATIO_PERCENT is None
    ):
        return

    try:
        normalized_run_id = _normalize_run_id(run_id)
        normalized_source = source.strip().lower() or "unknown"
        clamped_hits = max(int(cache_hits), 0)
        clamped_misses = max(int(cache_misses), 0)
        label_key = (normalized_run_id, normalized_source)

        with _canonical_cache_metrics_lock:
            previous_hits, previous_misses = _canonical_cache_previous_totals.get(label_key, (0, 0))
            delta_hits = max(clamped_hits - previous_hits, 0)
            delta_misses = max(clamped_misses - previous_misses, 0)
            # Preserve monotonic reference totals to avoid overcounting when
            # concurrent calls submit out-of-order cumulative snapshots.
            _canonical_cache_previous_totals[label_key] = (
                max(previous_hits, clamped_hits),
                max(previous_misses, clamped_misses),
            )

        if delta_hits > 0:
            _CANONICAL_READ_CACHE_HITS_TOTAL.labels(run_id=normalized_run_id, source=normalized_source).inc(delta_hits)
        if delta_misses > 0:
            _CANONICAL_READ_CACHE_MISSES_TOTAL.labels(run_id=normalized_run_id, source=normalized_source).inc(
                delta_misses
            )

        total = clamped_hits + clamped_misses
        ratio_percent = 0.0 if total <= 0 else (100.0 * (clamped_hits / total))
        _CANONICAL_READ_CACHE_HIT_RATIO_PERCENT.labels(run_id=normalized_run_id, source=normalized_source).set(
            ratio_percent
        )
    except Exception:
        logger.exception("Failed to record canonical read cache metrics")


def record_canonical_read_cache_disabled(run_id: str | None, source: str) -> None:
    """Set canonical metadata read cache ratio gauge to 0 for disabled path."""
    if _CANONICAL_READ_CACHE_HIT_RATIO_PERCENT is None:
        return
    try:
        normalized_run_id = _normalize_run_id(run_id)
        normalized_source = source.strip().lower() or "unknown"
        _CANONICAL_READ_CACHE_HIT_RATIO_PERCENT.labels(run_id=normalized_run_id, source=normalized_source).set(0.0)
    except Exception:
        logger.exception("Failed to record canonical read cache disabled metric")


def mount_metrics_endpoint(app: object, path: str = "/metrics") -> bool:
    """Mount Prometheus ASGI endpoint and return True when mounted.

    The `app` object is expected to expose a Starlette/FastAPI-compatible `mount`
    method. Any failure is logged and converted to a False return.
    """
    if not _is_histogram_supported() or make_asgi_app is None:
        return False
    try:
        mount = getattr(app, "mount")
        mount(path, make_asgi_app())
        return True
    except Exception:
        logger.exception("Failed to mount Prometheus endpoint", extra={"phase": "observability"})
        return False


def start_metrics_http_server_if_enabled() -> bool:
    """Start standalone Prometheus HTTP server when explicitly enabled.

    Controlled by:
    - MEDIA_MANAGER_METRICS_ENABLED: `1/true/yes/on` enables startup.
    - MEDIA_MANAGER_METRICS_PORT: optional integer port (default: 9000).
    """
    global _server_started
    if not _is_server_supported():
        return False

    enabled_raw = os.getenv("MEDIA_MANAGER_METRICS_ENABLED", "0").strip().lower()
    if enabled_raw not in {"1", "true", "yes", "on"}:
        return False

    raw_port = os.getenv("MEDIA_MANAGER_METRICS_PORT", "9000").strip()
    try:
        port = int(raw_port)
    except ValueError:
        logger.warning(
            "Invalid MEDIA_MANAGER_METRICS_PORT value; skipping metrics server startup",
            extra={"phase": "observability", "action": "METRICS_SERVER", "codes_extracted": raw_port},
        )
        return False

    with _server_lock:
        if _server_started:
            return True
        try:
            start_http_server(port)
            _server_started = True
            logger.info(
                "Prometheus metrics HTTP server started",
                extra={"phase": "observability", "action": "METRICS_SERVER", "files_count": port},
            )
            return True
        except Exception:
            logger.exception("Failed to start Prometheus metrics HTTP server", extra={"phase": "observability"})
            return False


def generate_metrics_text() -> bytes:
    """Return raw Prometheus exposition payload bytes for tests/debugging."""
    if generate_latest is None:
        return b""
    try:
        return generate_latest()
    except Exception:
        logger.exception("Failed to generate Prometheus metrics payload")
        return b""


def read_counter_value(metric_name: str, labels: Mapping[str, str]) -> float:
    """Read a counter sample value by metric name/labels from current registry."""
    metric_line_prefix = f"{metric_name}{{"
    payload = generate_metrics_text().decode("utf-8", errors="ignore")
    for line in payload.splitlines():
        if not line.startswith(metric_line_prefix):
            continue
        if all(f'{key}="{value}"' in line for key, value in labels.items()):
            value_raw = line.rsplit(" ", maxsplit=1)[-1]
            try:
                return float(value_raw)
            except ValueError:
                return 0.0
    return 0.0
