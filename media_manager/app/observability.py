"""Prometheus observability helpers for opt-in runtime metrics.

This module is intentionally fail-open:
- If prometheus_client is unavailable, all helpers become no-ops.
- Metrics setup errors never block planner/apply/CLI execution paths.
"""

from __future__ import annotations

import os
import threading
from collections.abc import Mapping

from media_manager.app.core.logging_config import get_logger

logger = get_logger(__name__)

try:
    from prometheus_client import Counter, Gauge, Histogram, REGISTRY, generate_latest, make_asgi_app, start_http_server
except Exception:  # pragma: no cover - fallback path when dependency is unavailable.
    Counter = None  # type: ignore[assignment]
    Gauge = None  # type: ignore[assignment]
    Histogram = None  # type: ignore[assignment]
    REGISTRY = None  # type: ignore[assignment]
    generate_latest = None  # type: ignore[assignment]
    make_asgi_app = None  # type: ignore[assignment]
    start_http_server = None  # type: ignore[assignment]

_server_lock = threading.Lock()
_registry_lock = threading.Lock()
_canonical_cache_metrics_lock = threading.Lock()
_server_started = False
_canonical_cache_previous_totals: dict[tuple[str, str], tuple[int, int]] = {}


def _is_histogram_supported() -> bool:
    return Histogram is not None


def _is_server_supported() -> bool:
    return start_http_server is not None


def _get_registered_collector(name: str):
    if REGISTRY is None:
        return None
    names_to_collectors = getattr(REGISTRY, "_names_to_collectors", {})
    return names_to_collectors.get(name)


def _get_or_create_counter(name: str, documentation: str, labelnames: tuple[str, ...]):
    """Return a registered Counter, reusing an existing collector when present.

    This keeps module import robust under reload/hot-reload scenarios where the
    default registry already contains the same metric names.
    """
    if Counter is None:
        return None

    try:
        with _registry_lock:
            existing = _get_registered_collector(name)
            if existing is not None:
                return existing
            return Counter(name, documentation, labelnames)
    except Exception:
        logger.exception("Failed to initialize counter", extra={"phase": "observability", "action": "METRICS_INIT"})
        return None


def _get_or_create_histogram(
    name: str,
    documentation: str,
    labelnames: tuple[str, ...],
    *,
    buckets: tuple[float, ...] | None = None,
):
    if Histogram is None:
        return None

    try:
        with _registry_lock:
            existing = _get_registered_collector(name)
            if existing is not None:
                return existing
            if buckets is None:
                return Histogram(name, documentation, labelnames)
            return Histogram(name, documentation, labelnames, buckets=buckets)
    except Exception:
        logger.exception("Failed to initialize histogram", extra={"phase": "observability", "action": "METRICS_INIT"})
        return None


def _get_or_create_gauge(name: str, documentation: str, labelnames: tuple[str, ...]):
    if Gauge is None:
        return None

    try:
        with _registry_lock:
            existing = _get_registered_collector(name)
            if existing is not None:
                return existing
            return Gauge(name, documentation, labelnames)
    except Exception:
        logger.exception("Failed to initialize gauge", extra={"phase": "observability", "action": "METRICS_INIT"})
        return None


